// Package codegen translates an already checked program into C11.
//
// Conventions of the generated C:
//   - user functions become mlc_fn_<name> (with the file's prefix, if
//     they come from an import); variables become l_<name> (or
//     lN_<name> when the name is redeclared in the function), which avoids collisions
//     with keywords and with the C library;
//   - each statement is preceded by #line, so that the runtime's errors and panics
//     point to the .mlc file;
//   - integer arithmetic goes through the runtime's MLC_* macros, which check
//     overflow and division by zero instead of falling into undefined behavior.
package codegen

import (
	"fmt"
	"math/big"
	"strings"

	"mlc/internal/ast"
	"mlc/internal/checker"
	"mlc/internal/token"
)

type gen struct {
	file   string
	info   *checker.Info
	buf    *strings.Builder
	indent int

	loops    []*loopCtx // open loops, the innermost last
	switches int        // open C switches (match on int)
	labels   int        // counter for unique label and temporary names
	// indexOverride replaces the index of s[i] with a temporary, so that an
	// index with an effect is computed only once in s[f()] += 1.
	indexOverride map[*ast.IndexExpr]string
	temps         []string // declarations of the temporaries of the function being generated

	joins      map[string]string // thread.join: the start of the records, by the result's C type
	spawnNames map[int]string    // thread.spawn: the record, by the function type's ID
}

// loopCtx follows a loop being generated. An MLC break inside a C switch
// would only leave the switch, so it becomes "goto label", with the label right
// after the loop.
type loopCtx struct {
	switches  int    // value of gen.switches when the loop opened
	label     string // exit label, created on first use
	needLabel bool
}

func Generate(file string, f *ast.File, info *checker.Info) string {
	g := &gen{file: file, info: info, buf: &strings.Builder{}, indexOverride: map[*ast.IndexExpr]string{}}
	g.raw("// Generated by mlc from %s. Do not edit.\n", file)
	g.raw("#include \"mlc_runtime.h\"\n")
	for _, h := range info.CHeaders {
		g.raw("#include %s\n", cString(h)) // extern "C" struct and const: C's own declarations
	}
	g.raw("\n")
	g.structs()
	// standard library functions implemented in the C runtime
	for _, fn := range info.Externs {
		params := []string{}
		for _, p := range fn.Params {
			params = append(params, cType(p.Type))
		}
		params = append(params, "const char *", "int")
		g.raw("%s %s(%s);\n", cType(fn.Result), fn.Native, strings.Join(params, ", "))
	}
	// C functions (extern "C" fn): a local name bound to the C symbol by an
	// assembly label, so as not to clash with what the headers already declare
	for _, fn := range info.CExterns {
		if fn.CHeader != "" {
			continue // the header declares it (or it's a macro): called by its name
		}
		params := []string{}
		for _, p := range fn.Params {
			params = append(params, cFFIType(p.Type))
		}
		if len(params) == 0 {
			params = append(params, "void")
		}
		g.raw("extern %s %s(%s) __asm__(MLC_SYM(%q));\n", cFFIType(fn.Result), fn.CName, strings.Join(params, ", "), fn.CSym)
	}
	g.threadDefs()
	for _, fn := range info.Funcs {
		g.raw("static MLC_MAYBE_UNUSED %s;\n", signature(fn)) // instances may go unused
	}
	for _, fn := range info.Callbacks {
		g.callbackWrapper(fn)
	}
	g.dropHelpers()
	g.chanDrops()
	g.raw("\n")
	for _, fn := range info.Funcs {
		g.function(fn)
	}
	if info.TestMode {
		g.testMain(info.Tests, info.Benches)
		return g.buf.String()
	}
	g.raw("int main(int argc, char **argv) {\n    mlc_args_init(argc, argv);\n    %s();\n    mlc_check_allocs();\n    return 0;\n}\n", info.Main.CName)
	return g.buf.String()
}

// testMain generates a test program's main: it runs the test whose index
// came as an argument (mlc test runs one process per test).
//
// With "bench i n", it runs benchmark i with b.n = n and reports the time.
func (g *gen) testMain(tests, benches []*checker.Func) {
	g.raw("int main(int argc, char **argv) {\n")
	if len(benches) > 0 {
		bt := benches[0].Params[0].Type.(*checker.Borrow).Elem
		g.raw("    int64_t bench, n;\n    if (mlc_bench_selected(argc, argv, &bench, &n)) {\n        mlc_args_init(1, argv);\n")
		g.raw("        %s b = %s;\n        b.f_n = n;\n        int64_t start = mlc_bench_now();\n        switch (bench) {\n", cType(bt), zeroValue(bt))
		for i, fn := range benches {
			g.raw("        case %d: %s(&b); break;\n", i, fn.CName)
		}
		g.raw("        default: return 2;\n        }\n        mlc_bench_report(mlc_bench_now() - start);\n        mlc_test_finish();\n        mlc_check_allocs();\n        return 0;\n    }\n")
	}
	g.raw("    int64_t test = mlc_test_selected(argc, argv);\n    mlc_args_init(1, argv);\n    switch (test) {\n")
	for i, fn := range tests {
		g.raw("    case %d: %s(); break;\n", i, fn.CName)
	}
	g.raw("    default: return 2;\n    }\n    mlc_test_finish();\n    mlc_check_allocs();\n    return 0;\n}\n")
}

func (g *gen) raw(format string, args ...any) {
	fmt.Fprintf(g.buf, format, args...)
}

// line writes a line of code at the current indentation.
func (g *gen) line(format string, args ...any) {
	g.buf.WriteString(strings.Repeat("    ", g.indent))
	fmt.Fprintf(g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func (g *gen) lineDirective(pos token.Pos) {
	g.raw("#line %d %s\n", pos.Line, cString(g.file))
}

func cType(t checker.Type) string {
	switch t := t.(type) {
	case *checker.Kept:
		return "void *" // the context C keeps (keep(x)): C's void *arg
	case *checker.Enum:
		return enumCType(t)
	case *checker.Array:
		return arrayCType(t)
	case *checker.Basic:
		if c, ok := numericC[checker.DefaultType(t)]; ok {
			return c
		}
	case *checker.Slice:
		return sliceCType(t)
	case *checker.Pointer:
		return cType(t.Elem) + " *"
	case *checker.Borrow:
		return cType(t.Elem) + " *"
	case *checker.FuncType:
		return funcCType(t)
	}
	if s, ok := t.(*checker.Struct); ok {
		if s.ThreadResult != nil {
			return "mlc_thread" // thread.Thread[R]: the runtime's record
		}
		if s.ChanEnd != 0 {
			return "mlc_chan" // chan.Sender[T] and chan.Receiver[T]: the runtime's channel
		}
		if s.MutexKind != 0 {
			return "mlc_mutex" // mutex.Mutex[T] and mutex.Guard[T]: the runtime's mutex
		}
		return structCType(s)
	}
	switch t {
	case checker.Int:
		return "int64_t"
	case checker.Bool:
		return "bool"
	case checker.String:
		return "mlc_str"
	case checker.Void:
		return "void"
	}
	panic(fmt.Sprintf("codegen: type without a C representation: %s", t))
}

func signature(fn *checker.Func) string {
	return signatureNamed(fn, fn.CName)
}

func signatureNamed(fn *checker.Func, name string) string {
	params := make([]string, len(fn.Params))
	for i, p := range fn.Params {
		params[i] = cType(p.Type) + " l_" + p.Name
	}
	list := "void"
	if len(params) > 0 {
		list = strings.Join(params, ", ")
	}
	return fmt.Sprintf("%s %s(%s)", cType(fn.Result), name, list)
}

func (g *gen) function(fn *checker.Func) {
	g.file = fn.File // each function points to its file (it also applies to the body)
	// The body is generated first, in a separate buffer, to know which
	// temporaries to declare at the start of the function.
	g.temps = nil
	outer, body := g.buf, &strings.Builder{}
	g.buf = body
	g.indent++
	for _, s := range fn.Decl.Body.Stmts {
		g.stmt(s)
	}
	g.indent--
	g.buf = outer

	big := fn.Frame >= checker.BigFrame
	g.lineDirective(fn.Decl.P)
	if big {
		g.raw("static MLC_NOINLINE %s {\n", signatureNamed(fn, fn.CName+"__frame"))
	} else {
		g.raw("static %s {\n", signature(fn))
	}
	for _, t := range g.temps {
		g.raw("    %s;\n", t)
	}
	g.buf.WriteString(body.String())
	g.raw("}\n\n")
	if big {
		g.frameCheck(fn)
	}
}

// frameCheck generates the entry function of a function with a large frame: it
// checks whether the frame fits in what's left of the stack (the frame estimated by the
// checker, plus the runtime's reserve) and only then calls the body, which isn't
// inlined so that the large frame only exists after the check.
func (g *gen) frameCheck(fn *checker.Func) {
	args := make([]string, len(fn.Params))
	for i, p := range fn.Params {
		args[i] = "l_" + p.Name
	}
	call := fmt.Sprintf("%s__frame(%s)", fn.CName, strings.Join(args, ", "))
	if fn.Result != checker.Void {
		call = "return " + call
	}
	g.lineDirective(fn.Decl.P)
	g.raw("static %s { MLC_STACK_NEED(%d); %s; }\n\n", signature(fn), fn.Frame, call) // on one line: the panic points at the declaration
}

func (g *gen) block(b *ast.Block) {
	g.indent++
	for _, s := range b.Stmts {
		g.stmt(s)
	}
	g.indent--
}

func (g *gen) stmt(s ast.Stmt) {
	switch s := s.(type) {
	case *ast.ConstDecl:
		// Constants don't exist in C: each use becomes the literal value.
	case *ast.ExprStmt, *ast.VarDecl, *ast.AssignStmt, *ast.IncDecStmt:
		g.lineDirective(s.Pos())
		g.line("%s;", g.simple(s))
	case *ast.IfStmt:
		g.lineDirective(s.P)
		g.ifStmt(s)
	case *ast.ForStmt:
		g.lineDirective(s.P)
		switch {
		case s.Var != nil:
			g.forIn(s)
		case s.Init == nil && s.Post == nil && s.Cond == nil:
			g.line("for (;;) {")
		case s.Init == nil && s.Post == nil:
			g.line("while (%s) {", g.cond(s.Cond))
		default:
			var init, cond, post string
			if s.Init != nil {
				init = g.simple(s.Init)
			}
			if s.Cond != nil {
				cond = g.cond(s.Cond)
			}
			if s.Post != nil {
				post = g.simple(s.Post)
			}
			g.line("for (%s; %s; %s) {", init, cond, post)
		}
		loop := &loopCtx{switches: g.switches}
		g.loops = append(g.loops, loop)
		g.block(s.Body)
		g.loops = g.loops[:len(g.loops)-1]
		g.line("}")
		if loop.needLabel {
			g.line("%s:;", loop.label)
		}
	case *ast.MatchStmt:
		g.lineDirective(s.P)
		if isEnum(g.typeOf(s.Subject)) {
			g.matchEnum(s)
		} else if checker.IsInteger(g.typeOf(s.Subject)) {
			g.matchSwitch(s)
		} else {
			g.matchIfChain(s)
		}
	case *ast.BranchStmt:
		g.lineDirective(s.P)
		loop := g.loops[len(g.loops)-1]
		if s.Tok == token.BREAK && g.switches > loop.switches {
			if !loop.needLabel {
				loop.needLabel = true
				loop.label = g.newName("mlc_break")
			}
			g.line("goto %s;", loop.label)
			return
		}
		// continue inside a C switch already goes to the loop, as in MLC.
		g.line("%s;", s.Tok)
	case *ast.ReturnStmt:
		g.lineDirective(s.P)
		if s.Value == nil {
			g.line("return;")
		} else {
			g.line("return %s;", g.expr(s.Value))
		}
	case *ast.Block:
		g.line("{")
		g.indent++
		for _, st := range s.Stmts {
			g.stmt(st)
		}
		g.indent--
		g.line("}")
	default:
		panic(fmt.Sprintf("codegen: unknown statement %T", s))
	}
}

func (g *gen) newName(prefix string) string {
	g.labels++
	return fmt.Sprintf("%s_%d", prefix, g.labels)
}

// armBody emits the body of a match arm, already inside braces.
func (g *gen) armBody(s ast.Stmt) {
	if b, ok := s.(*ast.Block); ok {
		g.block(b)
		return
	}
	g.indent++
	g.stmt(s)
	g.indent--
}

// matchSwitch emits a match on int as a C switch, which the C compiler
// can turn into a jump table. Each arm ends with break: there's no
// fallthrough. The checker guarantees there's a _ arm (the default).
func (g *gen) matchSwitch(s *ast.MatchStmt) {
	g.line("switch (%s) {", g.expr(s.Subject))
	g.switches++
	for _, arm := range s.Arms {
		var labels []string
		for _, p := range arm.Patterns {
			if p.Wildcard {
				labels = append(labels, "default:")
			} else {
				labels = append(labels, "case "+constant(g.info.Patterns[p], g.typeOf(s.Subject))+":")
			}
		}
		g.line("%s {", strings.Join(labels, " "))
		g.armBody(arm.Body)
		g.indent++
		g.line("break;")
		g.indent--
		g.line("}")
	}
	g.switches--
	g.line("}")
}

// matchIfChain emits a match on string or bool as an if/else chain. The
// value is computed only once, in a temporary.
func (g *gen) matchIfChain(s *ast.MatchStmt) {
	t := g.info.Types[s.Subject]
	if len(s.Arms) == 1 && s.Arms[0].Patterns[0].Wildcard {
		// Only the wildcard: no comparison, but the value is still computed.
		g.line("(void)%s;", g.expr(s.Subject))
		g.line("{")
		g.armBody(s.Arms[0].Body)
		g.line("}")
		return
	}
	tmp := g.newName("mlc_subject")
	g.line("{")
	g.indent++
	g.line("%s %s = %s;", cType(t), tmp, g.expr(s.Subject))
	for i, arm := range s.Arms {
		var conds []string
		for _, p := range arm.Patterns {
			if p.Wildcard {
				continue
			}
			switch v := g.info.Patterns[p].(type) {
			case string:
				conds = append(conds, fmt.Sprintf("mlc_string_eq(%s, MLC_STR_LIT(%s, %d))", tmp, cString(v), len(v)))
			case bool:
				if v {
					conds = append(conds, tmp)
				} else {
					conds = append(conds, "!"+tmp)
				}
			}
		}
		switch {
		case len(conds) == 0 || (i > 0 && i == len(s.Arms)-1):
			// The checker guarantees the match covers every value, so the
			// last arm doesn't need a condition. Without that, in a match with
			// true/false the C compiler doesn't see that every path returns.
			g.line("} else {")
		case i == 0:
			g.line("if (%s) {", strings.Join(conds, " || "))
		default:
			g.line("} else if (%s) {", strings.Join(conds, " || "))
		}
		g.armBody(arm.Body)
	}
	g.line("}")
	g.indent--
	g.line("}")
}

// ifStmt emits if/else; an "else if" becomes an if nested inside the else.
func (g *gen) ifStmt(s *ast.IfStmt) {
	g.line("if (%s) {", g.cond(s.Cond))
	g.block(s.Then)
	switch e := s.Else.(type) {
	case nil:
	case *ast.IfStmt:
		g.line("} else {")
		g.indent++
		g.ifStmt(e)
		g.indent--
	case *ast.Block:
		g.line("} else {")
		g.block(e)
	}
	g.line("}")
}

// simple translates a simple statement into a C expression (or declaration),
// without the final ';', to serve both as a statement and in the for's init/post.
func (g *gen) simple(s ast.Stmt) string {
	switch s := s.(type) {
	case *ast.ExprStmt:
		if call, ok := s.X.(*ast.CallExpr); ok && g.info.Calls[call].Builtin != checker.NoBuiltin && g.typeOf(s.X) != checker.Void {
			// thread.join(t) or str.format_len(...) as a statement: the value
			// (the last one of the comma expression) is discarded
			return "(void)" + g.expr(s.X)
		}
		return g.expr(s.X)
	case *ast.VarDecl:
		l := g.info.Decls[s]
		var value string
		if s.Value != nil {
			value = g.expr(s.Value)
		} else {
			value = zeroValue(l.Type)
		}
		return fmt.Sprintf("%s %s = %s", cType(l.Type), l.CName, value)
	case *ast.AssignStmt:
		pre := g.hoistIndex(s.Lhs, g.effectful(s.Rhs))
		defer g.dropIndex(s.Lhs)
		lhs := g.expr(s.Lhs)
		if s.Op == token.ASSIGN {
			if sel, ok := s.Lhs.(*ast.SelectorExpr); ok && isCStructBase(g.info.Types[sel.X]) {
				return sequence(pre, lhs+" = "+g.cFieldValue(lhs, g.info.Types[s.Lhs], s.Rhs))
			}
			return sequence(pre, lhs+" = "+g.expr(s.Rhs))
		}
		// x += v reads x before computing v, left to right.
		ops, v := g.operands([]ast.Expr{s.Lhs, s.Rhs})
		return sequence(append(pre, ops...), lhs+" = "+binop(checker.CompoundOp(s.Op), g.typeOf(s.Lhs), v[0], v[1]))
	case *ast.IncDecStmt:
		op := token.ADD
		if s.Op == token.DEC {
			op = token.SUB
		}
		pre := g.hoistIndex(s.X, false)
		defer g.dropIndex(s.X)
		x := g.expr(s.X)
		t := g.typeOf(s.X)
		return sequence(pre, x+" = "+arith(op, t, x, constant(big.NewInt(1), t)))
	}
	panic(fmt.Sprintf("codegen: unknown simple statement %T", s))
}

func zeroValue(t checker.Type) string {
	if en, ok := t.(*checker.Enum); ok {
		return "((" + enumCType(en) + "){0})" // first variant, zeroed fields
	}
	if a, ok := t.(*checker.Array); ok {
		return "((" + arrayCType(a) + "){0})"
	}
	if c, ok := numericC[t]; ok {
		return "((" + c + ")0)"
	}
	if s, ok := t.(*checker.Slice); ok {
		return "((" + sliceCType(s) + "){0})" // empty slice
	}
	if _, ok := t.(*checker.Pointer); ok {
		return "NULL" // only ?*T has a zero value; *T is always initialized
	}
	if _, ok := t.(*checker.FuncType); ok {
		return "NULL" // calling panics: every indirect call checks
	}
	if s, ok := t.(*checker.Struct); ok {
		return "((" + structCType(s) + "){0})"
	}
	switch t {
	case checker.Int:
		return "INT64_C(0)"
	case checker.Bool:
		return "false"
	case checker.String:
		return `MLC_STR_LIT("", 0)`
	}
	panic(fmt.Sprintf("codegen: type without a zero value: %s", t))
}

// cond translates the condition of if/while/for.
func (g *gen) cond(e ast.Expr) string {
	if b, ok := e.(*ast.BinaryExpr); ok {
		return g.binary(b, true)
	}
	return g.expr(e)
}

// ioPrint translates io.print, io.printf, str.format and str.format_len according to
// the checker's plan: the values go into temporaries (left to
// right, before writing anything) and each one is written by its
// write method, over an io.Writer on the stack. In str.format, the Writer
// writes into a destination registered in the runtime (mlc_sink_push), and the result
// is how many bytes were written.
func (g *gen) ioPrint(call *ast.CallExpr) string {
	plan := g.info.Prints[call]
	if plan.Mode == checker.PrintWriter {
		return g.writerPrintf(plan)
	}
	if plan.Mode == checker.PrintLog {
		return g.logPrintf(plan)
	}
	w := g.temp(plan.Writer)
	fd := plan.Fd
	switch plan.Mode {
	case checker.PrintSink:
		fd = -1 // io.SINK
	case checker.PrintCount:
		fd = -2 // io.COUNT
	}
	parts := writerInit(plan.Writer, w)
	parts = append(parts, fmt.Sprintf("%s.f_fd = INT64_C(%d)", w, fd))
	if plan.Mode == checker.PrintSink {
		// the destination is computed first, like the first argument
		parts = append(parts, fmt.Sprintf("%s.f_sink = mlc_sink_push(%s, __FILE__, __LINE__)", w, g.expr(plan.Dst)))
	}
	vals := make([]string, len(plan.Args))
	for i, a := range plan.Args {
		vals[i] = g.temp(plan.ArgTypes[i])
		parts = append(parts, vals[i]+" = "+g.expr(a))
	}
	parts = append(parts, g.printParts(plan, w, vals)...)
	parts = append(parts, fmt.Sprintf("%s(&%s)", plan.Flush.CName, w))
	switch plan.Mode {
	case checker.PrintSink:
		parts = append(parts, fmt.Sprintf("mlc_sink_pop(%s.f_sink, __FILE__, __LINE__)", w))
	case checker.PrintCount:
		parts = append(parts, w+".f_total")
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

// logPrintf translates lg.info("...", a, ...) and the other levels: the values
// are always computed (left to right), but only written
// if the level is enabled, into a Writer whose destination is the thread's line in the
// runtime (mlc_log_begin), handed whole to the logger (mlc_log_end).
func (g *gen) logPrintf(plan *checker.PrintPlan) string {
	lg := g.temp(g.typeOf(plan.Recv))
	parts := []string{lg + " = " + g.expr(plan.Recv)}
	vals := make([]string, len(plan.Args))
	for i, a := range plan.Args {
		vals[i] = g.temp(plan.ArgTypes[i])
		parts = append(parts, vals[i]+" = "+g.expr(a))
	}
	w := g.temp(plan.Writer)
	write := writerInit(plan.Writer, w)
	write = append(write, w+".f_fd = INT64_C(-1)", w+".f_sink = mlc_log_begin(__FILE__, __LINE__)")
	write = append(write, g.printParts(plan, w, vals)...)
	write = append(write, fmt.Sprintf("%s(&%s)", plan.Flush.CName, w))
	write = append(write, fmt.Sprintf("mlc_log_end(%s, INT64_C(%d), %s.f_sink, __FILE__, __LINE__)", lg, plan.Level, w))
	parts = append(parts, fmt.Sprintf("(mlc_log_enabled(%s, INT64_C(%d)) ? (%s) : (void)0)", lg, plan.Level, strings.Join(write, ", ")))
	return "(" + strings.Join(parts, ", ") + ")"
}

// printParts writes the format's parts (the fixed texts and the values,
// already computed in vals) into the Writer w.
func (g *gen) printParts(plan *checker.PrintPlan, w string, vals []string) []string {
	var parts []string
	for _, p := range plan.Parts {
		if p.Arg < 0 {
			parts = append(parts, fmt.Sprintf("%s(&%s, %s)", plan.PutStr.CName, w, constant(p.Lit, checker.String)))
			continue
		}
		v, t := vals[p.Arg], plan.ArgTypes[p.Arg]
		recv := "&" + v
		if p.Ptr {
			recv, v, t = v, "(*"+v+")", t.(*checker.Borrow).Elem // the borrow is already the pointer
		}
		if p.View {
			at := t.(*checker.Array)
			recv = fmt.Sprintf("&(%s){%s.a, INT64_C(%d)}", sliceCType(&checker.Slice{Elem: at.Elem}), v, at.Len)
		}
		write := func(writer string) string { return fmt.Sprintf("%s(%s, &%s)", p.Write.CName, recv, writer) }
		if p.Spec != nil && p.Spec.Text {
			write = func(writer string) string { return fmt.Sprintf("%s(&%s, %s)", plan.PutBytes.CName, writer, recv) }
		}
		if p.Spec == nil {
			parts = append(parts, write(w))
			continue
		}
		parts = append(parts, g.specWrite(plan, p.Spec, w, write)...)
	}
	return parts
}

// writerPrintf translates w.printf: the parts go into the caller's Writer,
// without creating a new one and without a flush. If there are specs, their fields
// are saved first and restored at the end, because the w.printf may be
// inside the write of a value that has its own spec.
func (g *gen) writerPrintf(plan *checker.PrintPlan) string {
	wp := g.temp(&checker.Pointer{Elem: plan.Writer})
	recv := g.expr(plan.Recv)
	switch g.typeOf(plan.Recv).(type) {
	case *checker.Borrow, *checker.Pointer:
	default:
		recv = "&" + recv
	}
	w := "(*" + wp + ")"
	parts := []string{wp + " = " + recv}
	vals := make([]string, len(plan.Args))
	for i, a := range plan.Args {
		vals[i] = g.temp(plan.ArgTypes[i])
		parts = append(parts, vals[i]+" = "+g.expr(a))
	}
	hasSpec := false
	for _, p := range plan.Parts {
		hasSpec = hasSpec || p.Spec != nil
	}
	var restore []string
	if hasSpec {
		for _, f := range []string{"width", "zero", "prec", "base", "upper", "alt"} {
			field := plan.Writer.Field(f)
			t := g.temp(field.Type)
			parts = append(parts, fmt.Sprintf("%s = %s.f_%s", t, w, f))
			restore = append(restore, fmt.Sprintf("%s.f_%s = %s", w, f, t))
		}
	}
	parts = append(parts, g.printParts(plan, w, vals)...)
	parts = append(parts, restore...)
	return "(" + strings.Join(parts, ", ") + ", (void)0)"
}

// writerInit zeroes the fields of the Writer w, except the buffer (an array): it's
// always written before being read (flush only reads buf[:n]), and zeroing the 256
// bytes on each io.printf cost more than formatting a number.
func writerInit(writer *checker.Struct, w string) []string {
	var parts []string
	for _, f := range writer.Fields {
		if _, isArray := f.Type.(*checker.Array); isArray {
			continue
		}
		parts = append(parts, fmt.Sprintf("%s.f_%s = %s", w, f.Name, zeroValue(f.Type)))
	}
	return parts
}

// specWrite writes a value with a spec ({:>8.2}): the Writer's
// fields apply during the write, and the alignment is done around it (to
// align right or center, the value is first written into a Writer that only
// counts, to know the size).
func (g *gen) specWrite(plan *checker.PrintPlan, spec *checker.FormatSpec, w string, write func(string) string) []string {
	var parts []string
	prec := 0
	if spec.Prec >= 0 {
		prec = spec.Prec + 1
	}
	numeric := spec.Zero || spec.Prec >= 0 || spec.Base != 0
	if numeric {
		parts = append(parts, fmt.Sprintf("%s(&%s, INT64_C(%d), %t, INT64_C(%d), INT64_C(%d), %t, %t)",
			plan.SpecBegin.CName, w, spec.Width, spec.Zero, prec, spec.Base, spec.Upper, spec.Alt))
	}
	if spec.Width > 0 && !spec.Zero {
		fill, align := fmt.Sprintf("(uint8_t)%d", spec.Fill), fmt.Sprintf("(uint8_t)%d", spec.Align)
		if spec.Align != '<' {
			m := g.temp(plan.Writer)
			parts = append(parts,
				fmt.Sprintf("%s = %s(&%s)", m, plan.Measure.CName, w),
				write(m),
				fmt.Sprintf("%s(&%s, %s, %s, INT64_C(%d), %s.f_chars)", plan.PadBefore.CName, w, fill, align, spec.Width, m))
		}
		start := g.temp(checker.Int)
		parts = append(parts,
			fmt.Sprintf("%s = %s.f_chars", start, w),
			write(w),
			fmt.Sprintf("%s(&%s, %s, %s, INT64_C(%d), %s.f_chars - %s)", plan.PadAfter.CName, w, fill, align, spec.Width, w, start))
	} else {
		parts = append(parts, write(w))
	}
	if numeric {
		parts = append(parts, fmt.Sprintf("%s(&%s)", plan.SpecEnd.CName, w))
	}
	return parts
}

func (g *gen) expr(e ast.Expr) string {
	// Constant expressions (literals, constants, arithmetic between constants)
	// were already computed by the checker: they become a literal of the final type.
	if v, ok := g.info.Values[e]; ok {
		return constant(v, g.typeOf(e))
	}
	if v, ok := g.info.EnumCtors[e]; ok {
		return g.enumCtor(e, v)
	}
	if fn, ok := g.info.FuncRefs[e]; ok {
		return fn.CName // the function used as a value: its address
	}
	if _, ok := g.info.Types[e].(*checker.OutHandle); ok {
		return "&" + g.expr(e.(*ast.UnaryExpr).X) // &h for a &?*X parameter: the handle's place
	}
	if l, ok := g.info.CConsts[e]; ok {
		return fmt.Sprintf("((%s)(%s))", cType(l.Type), l.CConst) // the header gives the value
	}
	switch e := e.(type) {
	case *ast.Ident:
		if l := g.info.Locals[e]; l != nil {
			return l.CName
		}
		if e.Name == "nil" {
			return "NULL"
		}
		return e.Name // true / false
	case *ast.UnaryExpr:
		switch e.Op {
		case token.SUB:
			return neg(g.typeOf(e.X), g.expr(e.X))
		case token.MUL:
			return "(*" + g.expr(e.X) + ")"
		case token.XOR:
			return fmt.Sprintf("((%s)~(%s))", numericC[g.typeOf(e)], g.expr(e.X))
		case token.AMP:
			if _, at := g.arrayOf(e.X); at != nil {
				if _, view := g.info.Types[e].(*checker.Borrow); view && !isArrayBorrow(g.info.Types[e]) {
					return g.arrayView(e.X) // &a as &[]T
				}
			}
			return g.borrow(e.X)
		}
		return "(!" + g.expr(e.X) + ")"
	case *ast.BinaryExpr:
		return g.binary(e, false)
	case *ast.IndexExpr:
		return g.index(e)
	case *ast.SelectorExpr:
		f := fieldCName(g.info.Types[e.X], e.Sel)
		access := g.expr(e.X) + "." + f
		if isPointer(g.info.Types[e.X]) {
			access = g.expr(e.X) + "->" + f
		}
		if b, ok := g.info.Types[e].(*checker.Borrow); ok && isCStructBase(g.info.Types[e.X]) {
			return fmt.Sprintf("((%s)(%s))", cType(b), access) // C's pointer, as the MLC handle type
		}
		return access
	case *ast.CompositeLit:
		return g.composite(e)
	case *ast.ArrayLit:
		return g.arrayLit(e)
	case *ast.CallExpr:
		callee := g.info.Calls[e]
		switch callee.Builtin {
		case checker.IoPrint:
			return g.ioPrint(e)
		case checker.ThreadSpawn:
			return g.threadSpawn(e)
		case checker.ThreadJoin:
			return g.threadJoin(e)
		case checker.ChanOp:
			return g.chanOp(e)
		case checker.MutexOp:
			return g.mutexOp(e)
		}
		switch callee.Builtin {
		case checker.Alloc:
			return g.alloc(e, callee)
		case checker.Free:
			if _, ok := g.info.Types[e.Args[0]].(*checker.Slice); ok {
				return "mlc_free(" + g.expr(e.Args[0]) + ".ptr)"
			}
			if t, ok := g.info.Types[e.Args[0]].(*checker.Enum); ok {
				return dropName(t) + "(" + g.expr(e.Args[0]) + ")" // the variant's owners
			}
			return "mlc_free(" + g.expr(e.Args[0]) + ")"
		case checker.Drop:
			// drop(x): frees x according to the type (mlc_drop_*); nothing if it isn't
			// an owner (T = int in an instance)
			if t := g.info.Types[e.Args[0]]; checker.IsOwner(t) {
				return dropName(t) + "(" + g.expr(e.Args[0]) + ")"
			}
			return "((void)(" + g.expr(e.Args[0]) + "))"
		case checker.Realloc:
			return g.realloc(e, callee)
		case checker.Take, checker.Replace:
			return g.takeReplace(e, callee)
		case checker.Keep:
			// moved to C: never freed, out of the leak count (a slice gives its array)
			if _, ok := g.info.Types[e.Args[0]].(*checker.Slice); ok {
				return "mlc_keep((" + g.expr(e.Args[0]) + ").ptr)"
			}
			return "mlc_keep(" + g.expr(e.Args[0]) + ")"
		case checker.Convert:
			return g.convert(e, callee)
		case checker.Len:
			if a, at := g.arrayOf(e.Args[0]); at != nil {
				return fmt.Sprintf("((void)%s, INT64_C(%d))", a, at.Len) // the size is fixed; the array is still evaluated
			}
			return g.sliceVal(e.Args[0]) + ".len"
		}
		if callee.Indirect {
			return g.indirectCall(e)
		}
		if callee.Func != nil && callee.Func.CSym != "" {
			return g.cCall(e, callee.Func)
		}
		pre, args := g.operands(g.info.CallArgs(e)) // in a method, the receiver comes first
		if callee.Func.Native != "" {
			// a runtime function: takes the file and line for the panics
			args = append(args, "__FILE__", "__LINE__")
			return sequence(pre, fmt.Sprintf("%s(%s)", callee.Func.Native, strings.Join(args, ", ")))
		}
		return sequence(pre, fmt.Sprintf("%s(%s)", callee.Func.CName, strings.Join(args, ", ")))
	}
	panic(fmt.Sprintf("codegen: unknown expression %T", e))
}

// indirectCall translates f(args) with f an fn value: f is computed first,
// then the arguments (left to right), and the call checks that
// f isn't null (the zero value of an fn).
func (g *gen) indirectCall(e *ast.CallExpr) string {
	fun := g.temp(g.info.Types[e.Fun])
	pre := []string{fun + " = " + g.expr(e.Fun)}
	more, args := g.operands(e.Args)
	pre = append(pre, more...)
	pre = append(pre, fmt.Sprintf("(%s == NULL ? mlc_null_fn(__FILE__, __LINE__) : (void)0)", fun))
	return sequence(pre, fmt.Sprintf("%s(%s)", fun, strings.Join(args, ", ")))
}

// cString writes s as a C string literal. Bytes outside printable ASCII
// become octal escapes, and '?' is escaped so it doesn't form trigraphs.
func cString(s string) string {
	var sb strings.Builder
	sb.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\' || c == '?':
			sb.WriteByte('\\')
			sb.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			sb.WriteByte(c)
		default:
			fmt.Fprintf(&sb, "\\%03o", c)
		}
	}
	sb.WriteByte('"')
	return sb.String()
}

// dropName is the function that frees a value of type t (drop in generic code).
func dropName(t checker.Type) string { return "mlc_drop_" + mangle(t) }

// dropHelpers writes a drop function for each owning type freed by
// drop: free of a simple owner, the free method of a struct with owners, or
// each element and then the slice.
func (g *gen) dropHelpers() {
	for _, t := range g.info.DropOrder {
		g.raw("static MLC_MAYBE_UNUSED void %s(%s v);\n", dropName(t), cType(t))
	}
	for _, t := range g.info.DropOrder {
		g.raw("static void %s(%s v) {\n", dropName(t), cType(t))
		switch tt := t.(type) {
		case *checker.Pointer:
			if s, ok := tt.Elem.(*checker.Struct); ok && s.ChanEnd != 0 {
				g.raw("    if (v != NULL) mlc_chan_close(v, %d);\n", s.ChanEnd) // drop of a channel end closes it
			} else if s, ok := tt.Elem.(*checker.Struct); ok && s.MutexKind == checker.MutexHandle {
				g.raw("    if (v != NULL) mlc_mutex_close(v);\n") // drop of a mutex handle closes it
			} else if s, ok := tt.Elem.(*checker.Struct); ok && s.Resource {
				g.raw("    if (v != NULL) %s(v);\n", g.info.DropFree[s].CName)
			} else {
				g.raw("    mlc_free(v);\n")
			}
		case *checker.Slice:
			if checker.IsOwner(tt.Elem) {
				g.raw("    for (int64_t i = 0; i < v.len; i++) %s(v.ptr[i]);\n", dropName(tt.Elem))
			}
			g.raw("    mlc_free(v.ptr);\n")
		case *checker.Enum:
			// frees the owners of whichever variant is there
			g.raw("    switch (v.tag) {\n")
			for _, vr := range tt.Variants {
				var frees []string
				for _, f := range vr.Fields {
					if checker.IsOwner(f.Type) {
						frees = append(frees, fmt.Sprintf("%s(v.u.v_%s.f_%s);", dropName(f.Type), vr.Name, f.Name))
					}
				}
				if len(frees) > 0 {
					g.raw("    case %d: %s break;\n", vr.Tag, strings.Join(frees, " "))
				}
			}
			g.raw("    default: break;\n    }\n")
		}
		g.raw("}\n")
	}
}

// cFFIType is the C type of a C function's parameter or result: string
// becomes const char * (MLC literals are zero-terminated) and &[]T becomes the
// pointer to the data.
func cFFIType(t checker.Type) string {
	if t == checker.String {
		return "const char *"
	}
	if b, ok := t.(*checker.Borrow); ok {
		if s, ok := b.Elem.(*checker.Slice); ok {
			return cType(s.Elem) + " *"
		}
	}
	if oh, ok := t.(*checker.OutHandle); ok {
		return cType(oh.Ptr) + "*" // &?*X: the address of the variable that receives the handle
	}
	if opt, ok := t.(*checker.OptArg); ok {
		return cFFIType(opt.Inner) // ?&T: the same pointer, which can be NULL
	}
	if ft, ok := t.(*checker.FuncType); ok {
		return callbackCType(ft)
	}
	return cType(t)
}

// callbackCType is the C type of a callback parameter: the function pointer
// in C's shape, where a slice is its pointer (the length is the next
// parameter, which C passes too).
func callbackCType(ft *checker.FuncType) string {
	params := make([]string, len(ft.Params))
	for i, p := range ft.Params {
		params[i] = cType(p)
		if el := sliceBorrowElem(p); el != nil {
			params[i] = cType(el) + " *"
		}
	}
	list := "void"
	if len(params) > 0 {
		list = strings.Join(params, ", ")
	}
	return fmt.Sprintf("%s (*)(%s)", cType(ft.Result), list)
}

// sliceBorrowElem is T in a &[]T, or nil.
func sliceBorrowElem(t checker.Type) checker.Type {
	if b, ok := t.(*checker.Borrow); ok {
		if s, ok := b.Elem.(*checker.Slice); ok {
			return s.Elem
		}
	}
	return nil
}

// cCall translates the call of a C function, converting the arguments.
func (g *gen) cCall(e *ast.CallExpr, fn *checker.Func) string {
	pre, args := g.operands(e.Args)
	if fn.CHeader != "" {
		// the header's name may be a macro that uses an argument twice: an
		// argument with effects is computed once, into a temporary, in order
		for i, a := range e.Args {
			if g.effectful(a) {
				t := g.temp(g.info.Types[a])
				pre = append(pre, t+" = "+args[i])
				args[i] = t
			}
		}
	}
	for i, p := range fn.Params {
		if i >= len(args) {
			break
		}
		switch {
		case isFuncType(p.Type):
			args[i] = callbackName(g.info.FuncRefs[e.Args[i]]) // the C wrapper, not the MLC function
			if fn.CHeader != "" {
				args[i] = "(void *)" + args[i] // the header's own function pointer type: the same pointer in the ABI
			}
		case p.Kept && !isKeptType(p.Type):
			args[i] = "mlc_keep(" + args[i] + ")" // the context now belongs to C, until the end
		case p.Type == checker.String:
			args[i] = "(" + args[i] + ").ptr"
		case isSliceBorrow(p.Type):
			args[i] = "(" + args[i] + ")->ptr"
		case isOptArgType(p.Type):
			switch {
			case g.info.Types[e.Args[i]] == checker.NilType:
				args[i] = "NULL"
			case isSliceBorrow(p.Type.(*checker.OptArg).Inner):
				args[i] = "(" + args[i] + ")->ptr"
			}
		}
	}
	if fn.CHeader != "" {
		// the header's name (a macro or an inline function too), with the
		// arguments already in temporaries: a macro that uses one twice
		// doesn't evaluate it twice. A pointer goes as void *, which C converts
		// to the header's own type (MLC's opaque types have other C names).
		for i, p := range fn.Params {
			if i < len(args) && isCPointer(p.Type) {
				args[i] = "(void *)(" + args[i] + ")"
			}
		}
		call := fmt.Sprintf("%s(%s)", fn.CSym, strings.Join(args, ", "))
		if isCPointer(fn.Result) {
			call = fmt.Sprintf("((%s)%s)", cType(fn.Result), call)
		}
		return sequence(pre, call)
	}
	return sequence(pre, fmt.Sprintf("%s(%s)", fn.CName, strings.Join(args, ", ")))
}

func isKeptType(t checker.Type) bool {
	_, ok := t.(*checker.Kept)
	return ok
}

// isCPointer says whether t is an object pointer in C (a borrow, a handle,
// an out parameter, a kept value or ?&T); a function pointer isn't.
func isCPointer(t checker.Type) bool {
	switch t.(type) {
	case *checker.Borrow, *checker.Pointer, *checker.OutHandle, *checker.OptArg, *checker.Kept:
		return true
	}
	return false
}

func isFuncType(t checker.Type) bool {
	_, ok := t.(*checker.FuncType)
	return ok
}

// callbackName is the C wrapper of an MLC function passed to C.
func callbackName(fn *checker.Func) string { return fn.CName + "__cb" }

// callbackWrapper writes the C wrapper of an MLC function passed to C: the
// same signature (MLC's C types are C's), with the runtime prepared around
// the call, since C may call from a thread MLC didn't create
// (mlc_cb_enter/mlc_cb_leave). The #line points at the function, so a stop
// in the wrapper (an interrupt) names it.
//
// A &[]T parameter arrives as C's pointer, with the length in the next
// parameter: the wrapper joins them into the slice the function receives (a
// negative length is an empty slice).
func (g *gen) callbackWrapper(fn *checker.Func) {
	g.file = fn.File
	params := make([]string, len(fn.Params))
	args := make([]string, len(fn.Params))
	slices := ""
	for i, p := range fn.Params {
		params[i] = cType(p.Type) + " l_" + p.Name
		args[i] = "l_" + p.Name
		if el := sliceBorrowElem(p.Type); el != nil && i+1 < len(fn.Params) {
			n := "l_" + fn.Params[i+1].Name
			params[i] = cType(el) + " *l_" + p.Name + "__p"
			slices += fmt.Sprintf(" %s l_%s__s = {.ptr = l_%s__p, .len = %s < 0 ? 0 : (int64_t)%s};",
				cType(p.Type.(*checker.Borrow).Elem), p.Name, p.Name, n, n)
			args[i] = "&l_" + p.Name + "__s"
		}
	}
	list := "void"
	if len(params) > 0 {
		list = strings.Join(params, ", ")
	}
	sig := fmt.Sprintf("%s %s(%s)", cType(fn.Result), callbackName(fn), list)
	call := fmt.Sprintf("%s(%s)", fn.CName, strings.Join(args, ", "))
	g.lineDirective(fn.Decl.P)
	if fn.Result == checker.Void {
		g.raw("static MLC_MAYBE_UNUSED %s {%s mlc_cb_frame mlc_cbf; mlc_cb_enter(&mlc_cbf, __FILE__, __LINE__); %s; mlc_cb_leave(&mlc_cbf); }\n",
			sig, slices, call)
		return
	}
	g.raw("static MLC_MAYBE_UNUSED %s {%s mlc_cb_frame mlc_cbf; mlc_cb_enter(&mlc_cbf, __FILE__, __LINE__); %s mlc_cbr = %s; mlc_cb_leave(&mlc_cbf); return mlc_cbr; }\n",
		sig, slices, cType(fn.Result), call)
}

func isOptArgType(t checker.Type) bool {
	_, ok := t.(*checker.OptArg)
	return ok
}

func isSliceBorrow(t checker.Type) bool {
	b, ok := t.(*checker.Borrow)
	if !ok {
		return false
	}
	_, ok = b.Elem.(*checker.Slice)
	return ok
}
