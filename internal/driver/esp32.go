package driver

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"mlc/internal/checker"
	"mlc/internal/token"
	"mlc/rt"
)

// The ESP32 target (mlc build -target esp32): instead of an executable,
// an ESP-IDF component with the generated C, the runtime and the entry that
// runs main in a FreeRTOS task. ESP-IDF compiles and flashes it. See
// docs/esp32.md.

// esp32Missing is what each standard module left out of the ESP32 runtime
// needs from a desktop system.
var esp32Missing = map[string]string{
	"std/fs":      "files and directories",
	"std/process": "processes",
	"std/signal":  "Unix signals",
	"std/sqlite":  "dlopen",
	"std/tls":     "dlopen and OpenSSL",
}

// esp32Stubs are the missing modules that another module may still import:
// the ESP32 runtime answers their functions with an error (std/tls says
// tls.UNAVAILABLE, as on a desktop without libssl), so std/http works
// without HTTPS. Only the program's own import is refused.
var esp32Stubs = map[string]bool{"std/tls": true}

// checkTarget refuses, in the program's files, an import that reaches a
// module the target doesn't have, directly or through another module.
func checkTarget(srcs []checker.Source, target string) []token.Error {
	if target != "esp32" {
		return nil
	}
	imports := map[string][]string{}
	for _, s := range srcs {
		for _, imp := range s.AST.Imports {
			imports[s.Path] = append(imports[s.Path], imp.Path)
		}
	}
	// reaches returns the first missing module that path leads to (a stub
	// counts only when it's the program's own import, direct)
	var reaches func(path string, direct bool, seen map[string]bool) string
	reaches = func(path string, direct bool, seen map[string]bool) string {
		if _, ok := esp32Missing[path]; ok && (direct || !esp32Stubs[path]) {
			return path
		}
		if seen[path] {
			return ""
		}
		seen[path] = true
		for _, p := range imports[path] {
			if m := reaches(p, false, seen); m != "" {
				return m
			}
		}
		return ""
	}
	var errs []token.Error
	for _, s := range srcs {
		if s.Std {
			continue // the error goes on the program's import, not inside the library
		}
		for _, imp := range s.AST.Imports {
			m := reaches(imp.Path, true, map[string]bool{})
			if m == "" {
				continue
			}
			msg := fmt.Sprintf("import %q: not available with -target esp32", imp.Path)
			if m != imp.Path {
				msg += fmt.Sprintf(" (it uses %s)", m)
			}
			msg += fmt.Sprintf(": %s needs %s, which the ESP32 runtime doesn't have", m, esp32Missing[m])
			errs = append(errs, token.Error{File: s.File, Pos: imp.P, Msg: msg})
		}
	}
	return errs
}

// esp32Marker is in the CMakeLists.txt that mlc writes: a folder with another
// CMakeLists.txt isn't overwritten.
const esp32Marker = "Generated by mlc build -target esp32"

// BuildESP32 writes into dir the ESP-IDF component of the program: mlc_app.c (the
// generated C), mlc_runtime.c and .h, mlc_main.c (app_main) and CMakeLists.txt.
func BuildESP32(file string, src []byte, dir string, read Loader, opts Options) error {
	opts.Target = "esp32"
	csrc, info, err := compileInfo(file, src, read, opts)
	if err != nil {
		return err
	}
	if len(info.Links) > 0 {
		return fmt.Errorf("link %q: with -target esp32, a C library comes in as an ESP-IDF component (REQUIRES in the project), not with link", info.Links[0])
	}
	cmake := filepath.Join(dir, "CMakeLists.txt")
	if old, err := os.ReadFile(cmake); err == nil && !strings.Contains(string(old), esp32Marker) {
		return fmt.Errorf("%s already exists and wasn't written by mlc: use an empty folder (or the project's main folder, without its CMakeLists.txt)", cmake)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	files := []struct{ name, content string }{
		{"mlc_app.c", csrc},
		{"mlc_runtime.h", rt.Header},
		{"mlc_runtime.c", rt.Source},
		{"mlc_main.c", rt.ESP32Main},
		{"CMakeLists.txt", rt.ESP32CMake},
	}
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(dir, f.name), []byte(f.content), 0o644); err != nil {
			return err
		}
	}
	return nil
}
