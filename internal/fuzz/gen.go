package fuzz

import (
	"fmt"
	"math/rand"
	"strings"
)

// Phase 3: random programs focused on ownership.
//
// The generator follows each variable's state (live, freed, nil) and, by
// construction, knows whether the program has an ownership bug:
//
//   - a valid program must be accepted by the checker (if it isn't, it's
//     a false-positive candidate, a case where the checker is
//     too conservative);
//   - a program with an injected bug (use after free, double free,
//     leak, dangling borrow, a struct freed with a live field,
//     an enum read after free) must be refused.
//
// The if conditions are known (one == 1 is always true, one == 2
// never), and the loops run at least once. The bug is only injected in
// code that runs, and always in a way execution sees: reading freed
// memory, freeing twice, leaving an allocation at the end. So, if the
// checker accepts a program with a bug, the oracle (AddressSanitizer and the
// allocation counter) confirms the hole.

// Program is a generated program.
type Program struct {
	Seed  int64
	Body  []*Node // main's body, without the fixed declarations
	Bug   string  // the injected bug ("" in a valid program)
	Lines int     // generated statements
}

// Node is a one-line statement, or a block (if, for, match) with children.
type Node struct {
	Line    string  // the statement, or the block's header ("if one == 1 {")
	Body    []*Node // the block's statements
	Else    []*Node // an if's else
	HasElse bool
	Close   bool // block: closes with "}"
	Bug     bool // the statement with the injected bug
}

// header is the fixed declarations of every generated program.
const header = `import "std/io"

struct Box {
    v int
}

struct Holder {
    b ?*Box
    s []byte
}

enum Bag {
    Empty
    Full(s []byte)
}

fn peek(b &Box) int {
    return b.v
}

fn size(s &[]byte) int {
    return len(s)
}

fn eat_box(b *Box) int {
    n := b.v
    free(b)
    return n
}

fn eat_bytes(s []byte) int {
    n := len(s)
    free(s)
    return n
}

fn make_box(v int) *Box {
    return alloc(Box{v: v})
}

fn pass_box(b *Box) *Box {
    b.v = b.v + 1
    return b
}

fn bag_peek(e &Bag) int {
    match *e {
        Empty => return 0
        Full(t) => return int(t[0])
    }
}

fn main() {
    acc := 0
    one := 1
`

// Source writes the program in MLC.
func (p *Program) Source() []byte {
	var b strings.Builder
	what := "valid"
	if p.Bug != "" {
		what = "with an injected bug: " + p.Bug
	}
	fmt.Fprintf(&b, "// generated by make fuzz (seed %d), %s\n", p.Seed, what)
	b.WriteString(header)
	writeNodes(&b, p.Body, 1)
	b.WriteString("    io.print(acc, one)\n}\n")
	return []byte(b.String())
}

func writeNodes(b *strings.Builder, ns []*Node, depth int) {
	ind := strings.Repeat("    ", depth)
	for _, n := range ns {
		b.WriteString(ind + n.Line + "\n")
		if !n.Close {
			continue
		}
		writeNodes(b, n.Body, depth+1)
		if n.HasElse {
			b.WriteString(ind + "} else {\n")
			writeNodes(b, n.Else, depth+1)
		}
		b.WriteString(ind + "}\n")
	}
}

// ---------- the variables' state ----------

type kind int

const (
	kBox    kind = iota // *Box
	kBytes              // []byte
	kOpt                // ?*Box
	kHolder             // *Holder (fields b ?*Box and s []byte)
	kBag                // Bag (an enum with a []byte)
	kRef                // &Box
)

type state int

const (
	live  state = iota
	dead        // freed or moved
	null        // ?*Box nil, or a Holder's field b
	empty       // the field s of a Holder coming from Holder{}: an empty slice
)

type gvar struct {
	name   string
	kind   kind
	st     state
	b, s   state // a Holder's fields
	full   bool  // Bag.Full (bag_peek reads the slice's memory)
	src    *gvar // kRef: the borrowed variable
	srcVer int   // kRef: src's version when the borrow was made
	ver    int   // changes on each move, free or assignment
}

// env is the state during generation: the visible variables, per scope.
type env struct {
	scopes [][]*gvar
}

func (e *env) clone() *env {
	m := map[*gvar]*gvar{}
	c := &env{}
	for _, sc := range e.scopes {
		var ns []*gvar
		for _, v := range sc {
			nv := *v
			m[v] = &nv
			ns = append(ns, &nv)
		}
		c.scopes = append(c.scopes, ns)
	}
	for _, sc := range c.scopes {
		for _, v := range sc {
			if v.src != nil {
				v.src = m[v.src]
			}
		}
	}
	return c
}

func (e *env) all() []*gvar {
	var out []*gvar
	for _, sc := range e.scopes {
		out = append(out, sc...)
	}
	return out
}

// pairs returns, for each variable of e, the corresponding one in o (a clone).
func (e *env) pairs(o *env) [][2]*gvar {
	var out [][2]*gvar
	for i, sc := range e.scopes {
		for j, v := range sc {
			out = append(out, [2]*gvar{v, o.scopes[i][j]})
		}
	}
	return out
}

// ---------- the generator ----------

type gen struct {
	r      *rand.Rand
	n      int  // next variable number
	budget int  // statements that can still be generated
	bug    bool // the bug still has to be injected
	p      *Program
}

// Generate generates a program. With withBug, a single bug is injected (if
// there's a chance to inject it in code that runs).
func Generate(seed int64, withBug bool) *Program {
	g := &gen{r: rand.New(rand.NewSource(seed)), budget: 8 + int(seed%5)*6, bug: withBug, p: &Program{Seed: seed}}
	e := &env{scopes: [][]*gvar{nil}}
	body := g.block(e, 0, true)
	if g.bug {
		// there was no chance on the way: a leak at the end
		body = append(body, g.inject(e, true)...)
	}
	body = append(body, g.closeScope(e, true)...)
	g.p.Body = body
	return g.p
}

func (g *gen) name(prefix string) string {
	g.n++
	return fmt.Sprintf("%s%d", prefix, g.n)
}

func (g *gen) k() int { return 1 + g.r.Intn(9) }

func line(s string) *Node { return &Node{Line: s} }

// block generates statements until the budget runs out or the draw stops. exec says
// whether the block runs.
func (g *gen) block(e *env, depth int, exec bool) []*Node {
	var out []*Node
	for g.budget > 0 {
		g.budget--
		if exec && g.bug && g.r.Intn(12) == 0 {
			out = append(out, g.inject(e, false)...)
			continue
		}
		switch c := g.r.Intn(20); {
		case c < 2 && depth < 2:
			out = append(out, g.ifStmt(e, depth, exec)...)
		case c < 3 && depth < 2:
			out = append(out, g.forStmt(e, depth, exec)...)
		case c < 7:
			out = append(out, g.declare(e)...)
		default:
			out = append(out, g.op(e)...)
		}
		if depth > 0 && g.r.Intn(4) == 0 {
			break
		}
	}
	return out
}

// declare creates a variable in the current scope.
func (g *gen) declare(e *env) []*Node {
	top := len(e.scopes) - 1
	add := func(v *gvar) { e.scopes[top] = append(e.scopes[top], v) }
	switch g.r.Intn(9) {
	case 0, 1:
		v := &gvar{name: g.name("b"), kind: kBox}
		add(v)
		if g.r.Intn(2) == 0 {
			return []*Node{line(fmt.Sprintf("%s := alloc(Box{v: %d})", v.name, g.k()))}
		}
		return []*Node{line(fmt.Sprintf("%s := make_box(%d)", v.name, g.k()))}
	case 2, 3:
		v := &gvar{name: g.name("s"), kind: kBytes}
		add(v)
		return []*Node{line(fmt.Sprintf("%s := alloc([]byte, %d)", v.name, g.k()))}
	case 4:
		v := &gvar{name: g.name("q"), kind: kOpt, st: null}
		add(v)
		return []*Node{line("var " + v.name + " ?*Box")}
	case 5:
		v := &gvar{name: g.name("h"), kind: kHolder, b: null, s: empty}
		if x, s := g.pick(e, kBox, live), g.pick(e, kBytes, live); x != nil && s != nil && g.r.Intn(2) == 0 {
			g.kill(x)
			g.kill(s)
			v.b, v.s = live, live
			add(v)
			return []*Node{line(fmt.Sprintf("%s := alloc(Holder{b: %s, s: %s})", v.name, x.name, s.name))}
		}
		add(v)
		return []*Node{line(v.name + " := alloc(Holder{})")}
	case 6:
		v := &gvar{name: g.name("e"), kind: kBag}
		if s := g.pick(e, kBytes, live); s != nil && g.r.Intn(3) > 0 {
			g.kill(s)
			v.full = true
			add(v)
			return []*Node{line(fmt.Sprintf("%s := Bag.Full(%s)", v.name, s.name))}
		}
		add(v)
		return []*Node{line(v.name + " := Bag.Empty")}
	case 7:
		x := g.pick(e, kBox, live)
		if x == nil {
			return nil
		}
		x.ver++ // a new borrow ends the previous ones (there are never two live)
		v := &gvar{name: g.name("r"), kind: kRef, src: x, srcVer: x.ver}
		add(v)
		return []*Node{line(v.name + " := &" + x.name), line("acc += " + v.name + ".v")}
	default:
		// move into a new variable
		x := g.pickAny(e, live, kBox, kBytes, kBag)
		if x == nil {
			return nil
		}
		v := &gvar{name: g.name(string(x.name[0])), kind: x.kind, full: x.full}
		g.kill(x)
		add(v)
		return []*Node{line(v.name + " := " + x.name)}
	}
}

// op is an operation on a variable that already exists, valid in its state.
func (g *gen) op(e *env) []*Node {
	vs := e.all()
	if len(vs) == 0 {
		return g.declare(e)
	}
	v := vs[g.r.Intn(len(vs))]
	n := v.name
	if v.kind != kRef {
		// while a borrow of v is still going to be used, v stays frozen
		// (even for reading): using v ends its borrows
		v.ver++
	}
	switch v.kind {
	case kBox:
		if v.st == dead {
			g.touch(v, live)
			if g.r.Intn(2) == 0 {
				return []*Node{line(fmt.Sprintf("%s = make_box(%d)", n, g.k()))}
			}
			return []*Node{line(fmt.Sprintf("%s = alloc(Box{v: %d})", n, g.k()))}
		}
		switch g.r.Intn(8) {
		case 0:
			return []*Node{line("acc += peek(&" + n + ")")}
		case 1:
			return []*Node{line("acc += " + n + ".v")}
		case 2:
			g.touch(v, live)
			return []*Node{line(n + ".v = acc % 100")}
		case 3:
			g.touch(v, live)
			return []*Node{line(n + " = pass_box(" + n + ")")}
		case 4:
			g.kill(v)
			return []*Node{line("acc += eat_box(" + n + ")")}
		case 5:
			if q := g.pickOpt(e); q != nil {
				g.kill(v)
				g.touch(q, live)
				return []*Node{line(q.name + " = " + n)}
			}
			return []*Node{line("acc += " + n + ".v")}
		case 6:
			if h := g.pickHolderField(e, "b"); h != nil {
				g.kill(v)
				h.b = live
				h.ver++
				return []*Node{line(h.name + ".b = " + n)}
			}
			return []*Node{line("acc += peek(&" + n + ")")}
		default:
			g.kill(v)
			return []*Node{line("free(" + n + ")")}
		}
	case kBytes:
		if v.st == dead {
			g.touch(v, live)
			return []*Node{line(fmt.Sprintf("%s = alloc([]byte, %d)", n, g.k()))}
		}
		switch g.r.Intn(7) {
		case 0:
			return []*Node{line("acc += size(&" + n + ")")}
		case 1:
			return []*Node{line("acc += int(" + n + "[0])")}
		case 2:
			g.touch(v, live)
			return []*Node{line(n + "[0] = byte(acc % 256)")}
		case 3:
			g.touch(v, live)
			return []*Node{line(fmt.Sprintf("%s = realloc(%s, %d)", n, n, g.k()))}
		case 4:
			g.kill(v)
			return []*Node{line("acc += eat_bytes(" + n + ")")}
		default:
			g.kill(v)
			return []*Node{line("free(" + n + ")")}
		}
	case kOpt:
		switch {
		case v.st == dead:
			if g.r.Intn(2) == 0 {
				g.touch(v, null)
				return []*Node{line(n + " = nil")}
			}
			g.touch(v, live)
			return []*Node{line(fmt.Sprintf("%s = make_box(%d)", n, g.k()))}
		case g.r.Intn(3) == 0:
			g.kill(v)
			return []*Node{line("free(" + n + ")")}
		case v.st == null && g.r.Intn(2) == 0:
			g.touch(v, live)
			return []*Node{line(fmt.Sprintf("%s = make_box(%d)", n, g.k()))}
		}
		return []*Node{{Line: "if " + n + " != nil {", Close: true, Body: []*Node{line("acc += " + n + ".v")}}}
	case kHolder:
		if v.st == dead {
			return nil // a freed Holder doesn't come back (the fields would have to be rebuilt)
		}
		switch g.r.Intn(7) {
		case 0:
			if v.b != dead {
				return []*Node{{Line: "if " + n + ".b != nil {", Close: true, Body: []*Node{line("acc += " + n + ".b.v")}}}
			}
		case 1:
			if v.s == dead {
				v.s = live
				v.ver++
				return []*Node{line(fmt.Sprintf("%s.s = alloc([]byte, %d)", n, g.k()))}
			}
			return []*Node{line("acc += size(&" + n + ".s)")}
		case 2:
			if v.s == live || v.s == empty {
				v.s = dead
				v.ver++
				return []*Node{line("free(" + n + ".s)")}
			}
		case 3:
			if v.b == live || v.b == null {
				v.b = dead
				v.ver++
				return []*Node{line("free(" + n + ".b)")}
			}
		case 4:
			if v.b != dead {
				q := &gvar{name: g.name("q"), kind: kOpt, st: v.b}
				v.b = dead
				v.ver++
				e.scopes[len(e.scopes)-1] = append(e.scopes[len(e.scopes)-1], q)
				return []*Node{line(q.name + " := " + n + ".b")}
			}
		case 5:
			if v.b == dead {
				v.b = null
				v.ver++
				return []*Node{line(n + ".b = nil")}
			}
		default:
			if v.b != live && v.s != live {
				g.kill(v)
				return []*Node{line("free(" + n + ")")}
			}
		}
		if v.s != dead {
			return []*Node{line("acc += size(&" + n + ".s)")}
		}
		return nil
	case kBag:
		if v.st == dead {
			g.touch(v, live)
			v.full = false
			return []*Node{line(n + " = Bag.Empty")}
		}
		switch g.r.Intn(4) {
		case 0, 1:
			return []*Node{line("acc += bag_peek(&" + n + ")")}
		case 2:
			g.kill(v)
			return []*Node{line("free(" + n + ")")}
		default:
			g.kill(v)
			t := g.name("t")
			return []*Node{{Line: "match " + n + " {", Close: true, Body: []*Node{
				line("Empty => {}"),
				{Line: "Full(" + t + ") => {", Close: true, Body: []*Node{line("acc += int(" + t + "[0])"), line("free(" + t + ")")}},
			}}}
		}
	case kRef:
		if v.src.st == live && v.src.ver == v.srcVer {
			return []*Node{line("acc += " + n + ".v")}
		}
	}
	return nil
}

// ifStmt generates an if with a known condition. The outer variables end
// both sides in the same state: the side where one stayed live frees it.
func (g *gen) ifStmt(e *env, depth int, exec bool) []*Node {
	taken := g.r.Intn(2) == 0
	cond := "one == 1"
	if !taken {
		cond = "one == 2"
	}
	n := &Node{Line: "if " + cond + " {", Close: true}
	te := e.clone()
	te.scopes = append(te.scopes, nil)
	n.Body = g.block(te, depth+1, exec && taken)
	n.Body = append(n.Body, g.closeScope(te, exec && taken)...)
	te.scopes = te.scopes[:len(te.scopes)-1]
	if g.r.Intn(2) == 0 {
		n.HasElse = true
		ee := e.clone()
		ee.scopes = append(ee.scopes, nil)
		n.Else = g.block(ee, depth+1, exec && !taken)
		n.Else = append(n.Else, g.closeScope(ee, exec && !taken)...)
		ee.scopes = ee.scopes[:len(ee.scopes)-1]
		g.reconcile(te, ee, &n.Body, &n.Else)
		g.adopt(e, te)
	} else {
		var none []*Node
		g.reconcile(te, e.clone(), &n.Body, &none)
		if len(none) > 0 {
			n.HasElse, n.Else = true, none
		}
		g.adopt(e, te)
	}
	return []*Node{n}
}

// forStmt generates a loop that runs 2 to 4 times, sometimes with a break on the
// last iteration. The outer variables end each iteration in the state they
// entered.
func (g *gen) forStmt(e *env, depth int, exec bool) []*Node {
	i := g.name("i")
	k := 2 + g.r.Intn(3)
	n := &Node{Line: fmt.Sprintf("for %s := 0; %s < %d; %s++ {", i, i, k, i), Close: true}
	if g.r.Intn(3) == 0 {
		n.Body = append(n.Body, &Node{Line: fmt.Sprintf("if %s == %d {", i, k-1), Close: true, Body: []*Node{line("break")}})
	}
	// a Holder with an empty field s (from Holder{}) doesn't become empty again
	// after an iteration that rebuilds it: before the loop, s gets memory
	var pre []*Node
	for _, v := range e.all() {
		if v.kind == kHolder && v.st == live && v.s == empty {
			pre = append(pre, line("free("+v.name+".s)"), line(fmt.Sprintf("%s.s = alloc([]byte, %d)", v.name, g.k())))
			v.s = live
			v.ver++
		}
	}
	be := e.clone()
	be.scopes = append(be.scopes, nil)
	// the outer borrows aren't used inside the loop: the source may
	// change in one iteration and the borrow would be used in the next
	for _, v := range be.all() {
		if v.kind == kRef {
			v.srcVer = -1
		}
	}
	n.Body = append(n.Body, g.block(be, depth+1, exec)...)
	n.Body = append(n.Body, g.closeScope(be, exec)...)
	be.scopes = be.scopes[:len(be.scopes)-1]
	start := e.clone()
	var none []*Node
	g.reconcileTo(be, start, &n.Body, &none)
	// an outer borrow whose source changed in the loop is no longer valid afterwards
	for _, pr := range e.pairs(be) {
		if pr[0].ver != pr[1].ver {
			pr[0].ver = pr[1].ver + 1000
		}
	}
	return append(pre, n)
}

// reconcile makes the state of the outer variables equal at the end of both sides of
// an if: one that ended differently is freed (or becomes nil) on both.
func (g *gen) reconcile(a, b *env, an, bn *[]*Node) {
	for _, pr := range a.pairs(b) {
		x, y := pr[0], pr[1]
		if !same(x, y) {
			*an, *bn = append(*an, g.settle(x)...), append(*bn, g.settle(y)...)
		}
		if x.ver != y.ver {
			// it changed on some side: a borrow of it made before the if is no longer valid
			v := max(x.ver, y.ver) + 1
			x.ver, y.ver = v, v
		}
	}
}

func same(x, y *gvar) bool {
	switch x.kind {
	case kRef:
		return true
	case kHolder:
		return x.st == y.st && x.b == y.b && x.s == y.s
	case kBag:
		return x.st == y.st && x.full == y.full
	}
	return x.st == y.st
}

// reconcileTo takes the variables of a (the end of a loop iteration) to the state
// of to (the start), adding the statements to an.
func (g *gen) reconcileTo(a, to *env, an, _ *[]*Node) {
	for _, pr := range to.pairs(a) {
		want, x := pr[0], pr[1]
		*an = append(*an, g.restore(x, want)...)
	}
}

// settle takes an outer variable to a state that doesn't depend on the path:
// freed (or nil, for ?*Box), with a Holder's fields freed.
func (g *gen) settle(v *gvar) []*Node {
	var out []*Node
	switch v.kind {
	case kOpt:
		if v.st == live {
			out = append(out, line("free("+v.name+")"))
		}
		if v.st != null {
			out = append(out, line(v.name+" = nil"))
			g.touch(v, null)
		}
	case kHolder:
		if v.st == dead {
			return nil
		}
		if v.b == live || v.b == null {
			out = append(out, line("free("+v.name+".b)"))
		}
		if v.s == live || v.s == empty {
			out = append(out, line("free("+v.name+".s)"))
		}
		out = append(out, line("free("+v.name+")"))
		v.b, v.s = dead, dead
		g.kill(v)
	case kRef:
		v.srcVer = -1
	default:
		if v.st == live {
			out = append(out, line("free("+v.name+")"))
			g.kill(v)
		}
	}
	return out
}

// restore takes x to want's state (the same as at the start of the iteration).
func (g *gen) restore(x, want *gvar) []*Node {
	var out []*Node
	switch x.kind {
	case kRef:
		return nil
	case kHolder:
		if want.st == dead {
			return nil // it already came in freed: nothing inside revived it
		}
		if x.st == dead {
			// freed inside the iteration: rebuilt empty
			out = append(out, line(x.name+" = alloc(Holder{})"))
			x.st, x.b, x.s = live, null, empty
		}
		if x.b == live {
			out = append(out, line("free("+x.name+".b)"))
		}
		if x.b != null {
			out = append(out, line(x.name+".b = nil"))
		}
		if want.b == live {
			out = append(out, line(fmt.Sprintf("%s.b = make_box(%d)", x.name, g.k())))
		}
		// want.s is never empty (forStmt normalizes it before the loop)
		if x.s != want.s {
			if x.s == live || x.s == empty {
				out = append(out, line("free("+x.name+".s)"))
			}
			if want.s == live {
				out = append(out, line(fmt.Sprintf("%s.s = alloc([]byte, %d)", x.name, g.k())))
			}
		}
		x.b, x.s = want.b, want.s
		return out
	}
	if x.st == live && want.st != live {
		out = append(out, line("free("+x.name+")"))
	}
	if x.kind == kOpt && want.st == null && x.st != null {
		out = append(out, line(x.name+" = nil"))
	}
	if want.st == live && x.st != live {
		switch x.kind {
		case kBox, kOpt:
			out = append(out, line(fmt.Sprintf("%s = make_box(%d)", x.name, g.k())))
		case kBytes:
			out = append(out, line(fmt.Sprintf("%s = alloc([]byte, %d)", x.name, g.k())))
		case kBag:
			if want.full {
				out = append(out, line(fmt.Sprintf("%s = Bag.Full(alloc([]byte, %d))", x.name, g.k())))
			} else {
				out = append(out, line(x.name+" = Bag.Empty"))
			}
		}
	}
	x.st = want.st
	return out
}

// adopt copies into e the state of o's variables (a clone of e).
func (g *gen) adopt(e, o *env) {
	for _, pr := range e.pairs(o) {
		src := pr[0].src
		*pr[0] = *pr[1]
		pr[0].src = src
	}
}

// closeScope frees the live variables of the inner scope, at the end of the
// block (a nil ?*Box also goes through free, which does nothing: that way every
// declared variable is used).
func (g *gen) closeScope(e *env, exec bool) []*Node {
	top := len(e.scopes) - 1
	var out []*Node
	for _, v := range e.scopes[top] {
		if v.kind == kOpt && v.st == null {
			out = append(out, line("free("+v.name+")"))
			g.kill(v)
			continue
		}
		out = append(out, g.settle(v)...)
	}
	return out
}

// ---------- bugs ----------

// inject writes a bug execution sees, at the current point (which runs).
func (g *gen) inject(e *env, atEnd bool) []*Node {
	bug := func(s string) *Node { return &Node{Line: s, Bug: true} }
	kinds := []string{"leak"}
	if g.pick(e, kBox, live) != nil {
		kinds = append(kinds, "use after free", "double free", "borrow after free", "use after move and free")
	}
	if g.pick(e, kBytes, live) != nil {
		kinds = append(kinds, "byte read after free")
	}
	for _, v := range e.all() {
		if v.kind == kBag && v.st == live && v.full {
			kinds = append(kinds, "enum read after free")
			break
		}
	}
	for _, v := range e.all() {
		if v.kind == kHolder && v.st == live && (v.b == live || v.s == live) {
			kinds = append(kinds, "struct freed with a live field")
			break
		}
	}
	if atEnd {
		kinds = kinds[:1]
	}
	k := kinds[g.r.Intn(len(kinds))]
	g.bug = false
	g.p.Bug = k
	switch k {
	case "use after free":
		x := g.pick(e, kBox, live)
		g.kill(x)
		return []*Node{line("free(" + x.name + ")"), bug("acc += " + x.name + ".v")}
	case "double free":
		x := g.pick(e, kBox, live)
		g.kill(x)
		return []*Node{line("free(" + x.name + ")"), bug("free(" + x.name + ")")}
	case "borrow after free":
		x := g.pick(e, kBox, live)
		r := g.name("r")
		g.kill(x)
		return []*Node{line(r + " := &" + x.name), line("acc += " + r + ".v"), line("free(" + x.name + ")"), bug("acc += " + r + ".v")}
	case "use after move and free":
		x := g.pick(e, kBox, live)
		y := g.name("b")
		g.kill(x)
		return []*Node{line(y + " := " + x.name), line("free(" + y + ")"), bug("acc += " + x.name + ".v")}
	case "byte read after free":
		s := g.pick(e, kBytes, live)
		g.kill(s)
		return []*Node{line("free(" + s.name + ")"), bug("acc += int(" + s.name + "[0])")}
	case "enum read after free":
		for _, v := range e.all() {
			if v.kind == kBag && v.st == live && v.full {
				g.kill(v)
				return []*Node{line("free(" + v.name + ")"), bug("acc += bag_peek(&" + v.name + ")")}
			}
		}
	case "struct freed with a live field":
		for _, v := range e.all() {
			if v.kind == kHolder && v.st == live && (v.b == live || v.s == live) {
				var out []*Node
				// the field that doesn't leak is freed first, so there's a single leak
				if v.b == live {
					if v.s == live || v.s == empty {
						out = append(out, line("free("+v.name+".s)"))
					}
				} else if v.b == null {
					out = append(out, line("free("+v.name+".b)"))
				}
				g.kill(v)
				return append(out, bug("free("+v.name+")"))
			}
		}
	}
	// leak: an allocation that's never freed
	v := g.name("leak")
	return []*Node{bug(fmt.Sprintf("%s := alloc(Box{v: %d})", v, g.k())), line("acc += " + v + ".v")}
}

// ---------- helpers ----------

func (g *gen) pick(e *env, k kind, st state) *gvar {
	var c []*gvar
	for _, v := range e.all() {
		if v.kind == k && v.st == st {
			c = append(c, v)
		}
	}
	if len(c) == 0 {
		return nil
	}
	return c[g.r.Intn(len(c))]
}

func (g *gen) pickAny(e *env, st state, ks ...kind) *gvar {
	var c []*gvar
	for _, v := range e.all() {
		for _, k := range ks {
			if v.kind == k && v.st == st {
				c = append(c, v)
			}
		}
	}
	if len(c) == 0 {
		return nil
	}
	return c[g.r.Intn(len(c))]
}

// pickOpt finds a ?*Box that can receive a value (nil or freed).
func (g *gen) pickOpt(e *env) *gvar {
	var c []*gvar
	for _, v := range e.all() {
		if v.kind == kOpt && v.st != live {
			c = append(c, v)
		}
	}
	if len(c) == 0 {
		return nil
	}
	return c[g.r.Intn(len(c))]
}

// pickHolderField finds a live Holder whose field b can receive a value.
func (g *gen) pickHolderField(e *env, _ string) *gvar {
	for _, v := range e.all() {
		if v.kind == kHolder && v.st == live && v.b != live {
			return v
		}
	}
	return nil
}

func (g *gen) kill(v *gvar) { g.touch(v, dead) }

func (g *gen) touch(v *gvar, st state) {
	v.st = st
	v.ver++
}
